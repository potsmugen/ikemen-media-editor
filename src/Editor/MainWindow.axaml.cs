    private async void OnTabChanged(object? sender, SelectionChangedEventArgs e)
    {
        // TabControl can raise SelectionChanged during InitializeComponent,
        // before every x:Name field has been assigned. The constructor sets
        // the initial tab status after InitializeComponent returns.
        if (CursorStatusText is null) return;
        // SelectionChanged bubbles: list selections inside a tab land here too and must not re-run tab logic.
        if (!ReferenceEquals(e.Source, Tabs)) return;
        SyncFloatingVisibility();

        try
        {
            if (_suppressEvents) return;
            if (Tabs?.SelectedIndex == 2) UpdateFrameButtons(); // a sprite file may have opened meanwhile
            if (Tabs?.SelectedIndex != 0)
            {
                CancelPick(restoreSelection: false);
                if (_paintBaseline is not null && !await ResolvePendingPaintBeforeSwitch())
                {
                    _suppressEvents = true;
                    Tabs!.SelectedIndex = 0;
                    _suppressEvents = false;
                    return;
                }
            }
            if (Tabs?.SelectedIndex != 1)
                CancelPaletteLinkPick(restoreSelection: false);
            if (Tabs?.SelectedIndex != 3 && _soundEditBaseline is not null && !await ResolvePendingSoundEditsBeforeSwitch())
            {
                _suppressEvents = true;
                Tabs!.SelectedIndex = 3;
                _suppressEvents = false;
                return;
            }
            // Leaving the Palettes tab: any slider preview that wasn't
            // committed is lost, same as pressing Reset — no dialog, Commit
            // is the only way to keep it, so there's nothing to revert to.
            if (_editingPalette is not null) DiscardPendingColorAdjust();
            int tab = Tabs?.SelectedIndex ?? 0;
            // Leaving Animations or Palettes: the sprite shown there becomes the selected sprite (one way only).
            Sprite? shown = !_settings.SyncSpriteAcrossTabs ? null
                : _lastTab == 2 && tab != 2 ? _animSprite
                : _lastTab == 1 && tab == 0 ? PalettePreviewSprite()
                : null;
            if (shown is not null && _file is not null && _file.PositionOf(shown) is var shownPos and >= 0)
            {
                // Already current means the selection is right; reselecting would collapse a multi-selection.
                if (!ReferenceEquals(shown, _current)) SelectSprite(shownPos);
                // The list was hidden when the selection moved, so scroll once the tab is laid out.
                if (tab == 0) ScrollSpriteIntoView(shown);
            }
            if (tab == 0 && _lastTab != 0)
            {
                _paletteOverride = -1;
                _suppressEvents = true;
                PaletteBox.SelectedIndex = 0;
                _suppressEvents = false;
                RefreshSprite();
            }
            _lastTab = tab;
            _spriteCursorPosition = null;
            _animCursorPosition = null;
            CursorStatusText.Text = "";
            UpdateTabStatusVisibility(tab);
            UpdateCursorStatus();
            FitPanelsForTab(tab);
            RestoreFloatingPanels(tab);
            switch (Tabs?.SelectedIndex)
            {
                case 2: ShowFrame(); break;        // sprites may have changed since last look
                case 1: RefreshPaletteTab(); break;
                default: Pause(); break;       // stop playback when leaving the tab
            }
            FocusTabList();
        }
        catch (Exception ex)
        {
            await Failed("OnTabChanged", ex);
        }
    }

    private void UpdateStatus()
    {
        if (_file is null || _current is null)
        {
            StatusText.Text = _file is null ? "No file loaded" : "No sprite selected";
            return;
        }

        var s = _current;
        var parts = new List<string>
        {
            $"v{_file.Version}",
            $"{s.Group},{s.Index}",
            $"{s.Width}x{s.Height}",
            $"axis {s.AxisX},{s.AxisY}",
            s.SrcFormat.ToString().ToLowerInvariant() + $" {s.SrcDepth}-bit",
        };
        if (_visible.Count != _file.Sprites.Count) parts.Add($"{_visible.Count} of {_file.Sprites.Count} shown");
        if (s.SharesWith is { } t) parts.Add($"linked to {t.Group},{t.Index}");
        if (s.DecodeError is not null) parts.Add($"DECODE FAILED: {s.DecodeError}");
        if (_dirty) parts.Add("unsaved changes");
        StatusText.Text = string.Join("   |   ", parts);
    }

