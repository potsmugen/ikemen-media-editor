    /// <summary>
    /// Runs an edit and records how to reverse it. Everything that changes the
    /// file goes through here so nothing escapes the undo stack.
    /// </summary>
    private void Edit(string name, Action apply, Action undo, string? mergeKey = null, string kind = SffKind)
    {
        _undo.Do(name, () => { apply(); AfterEdit(); }, () => { undo(); AfterEdit(); }, mergeKey);
        if (kind.StartsWith("palette:", StringComparison.Ordinal))
        {
            if (!_undo.Tag(kind)) _undo.Untracked(kind);
            foreach (var palette in _standalonePalettes.Where(p => StandalonePaletteKindFor(p) == kind))
                palette.Dirty = _undo.Differs(kind);
            UpdateTitle();
        }
        else MarkDirty();
    }

    private string StandalonePaletteKindFor(Palette palette)
    {
        if (!_standalonePaletteKinds.TryGetValue(palette, out var kind))
            _standalonePaletteKinds.Add(palette, kind = $"palette:{Guid.NewGuid():N}");
        return kind;
    }

    private void MarkStandalonePaletteDirty(Palette palette)
    {
        string kind = StandalonePaletteKindFor(palette);
        if (!_undo.Tag(kind)) _undo.Untracked(kind);
        palette.Dirty = _undo.Differs(kind);
        UpdateTitle();
    }

    /// <summary>Rebuilds whatever an edit might have invalidated.</summary>
    private void AfterEdit()
    {
        if (_file is null)
        {
            RebuildPaletteList();
            RefreshPaletteTab();
            UpdateTitle();
            return;
        }
        RebuildPaletteList();
        UpdateSffInfo();
        int keep = _current is null ? -1 : _file.PositionOf(_current);
        // Capture the multi-selection before ApplyFilter rebuilds the rows (which recreates the row
        // objects and drops the ListBox selection) so it can be restored afterwards by sprite identity.
        var selectedSprites = SelectedSpriteTargets();
        // Keep the selection plumbing quiet: each unsuppressed SelectedIndex set
        // below used to fire OnSpriteSelected and re-decode the sprite on the
        // way past. The one RefreshSprite at the end covers all of it.
        _suppressEvents = true;
        ApplyFilter();
        RestoreSpriteSelection(selectedSprites);
        // Only re-select when the current sprite isn't selected already: the rows now survive an
        // edit, so re-selecting unconditionally would collapse a multi-selection to one row (and
        // scroll to it) after every keystroke, spinner nudge or paint stroke.
        if (keep >= 0 && !SpriteRowSelected(keep)) SelectSprite(keep);
        _suppressEvents = false;
        // ApplyFilter leaves row 0 selected when the current sprite is gone;
        // adopt it here, where the suppressed event used to.
        if (_current is null && SpriteList.SelectedIndex >= 0 && SpriteList.SelectedIndex < _visible.Count)
            _current = _file.Sprites[_visible[SpriteList.SelectedIndex]];
        RefreshPaletteTab();
        RefreshSprite();
    }

    private void OnUndo(object? sender, RoutedEventArgs e)
    {
        // Paint Mode edits are live but pending. Undo the most recent stroke
        // (or floating paste move) without discarding earlier strokes in the
        // same pending session; Commit still turns the remaining session into
        // one normal undo entry.
        if (_paintStrokeBefore is { } stroke && _paintStrokeSprite is { } strokeSprite
            && ReferenceEquals(strokeSprite, _current) && strokeSprite.Indexed is not null)
        {
            strokeSprite.Indexed = (byte[])stroke.Clone();
            strokeSprite.PixelsDirty = _paintStrokeBeforeDirty;
            _paintStrokeBefore = null;
            _paintStrokeSprite = null;
            _floatingPaste = null;
            SpriteCanvas.SetSelection(null);
            SpriteCanvas.Show(strokeSprite, ActivePalette(), _showMask);
            PaintCommitButton.IsEnabled = PaintResetButton.IsEnabled = _paintBaseline is not null;
            SyncDirtyFromUndo();
            ResetPlaybackCaches();
            StatusText.Text = "Undid last paint stroke.";
            return;
        }
        if (!_undo.CanUndo) return;
        var name = _undo.UndoName;
        CrashLog.Trace($"[undo] begin: {name}");
        var view = _undo.UndoView as UndoView;
        GoToUndoTab(view);
        ClearSoundSelection(); // undo can change a sound's length; a kept selection may no longer fit
        _undo.Undo();
        ResetPlaybackCaches(); // undo can run while playing; cached sprites may be stale
        CrashLog.Trace($"[undo] complete: {name}");
        // The palette now holds the restored colors; rebase so they don't read as a pending adjustment.
        ResetColorAdjustBase();
        SyncDirtyFromUndo();
        GoToUndoItem(view);
        StatusText.Text = $"Undid {name}";
    }

    private void OnRedo(object? sender, RoutedEventArgs e)
    {
        if (!_undo.CanRedo) return;
        var name = _undo.RedoName;
        CrashLog.Trace($"[redo] begin: {name}");
        var view = _undo.RedoView as UndoView;
        GoToUndoTab(view);
        ClearSoundSelection();
        _undo.Redo();
        ResetPlaybackCaches();
        CrashLog.Trace($"[redo] complete: {name}");
        // The palette now holds the restored colors; rebase so they don't read as a pending adjustment.
        ResetColorAdjustBase();
        SyncDirtyFromUndo();
        GoToUndoItem(view);
        StatusText.Text = $"Redid {name}";
    }

    /// <summary>Where an edit was made: the tab and what was selected there.</summary>
    private sealed record UndoView(int Tab, object? Item);

    private UndoView CaptureUndoView()
    {
        int tab = Tabs?.SelectedIndex ?? 0;
        object? item = tab switch
        {
            0 => _current,
            2 => _action,
            1 => _editingPalette is not null && _standalonePalettes.Contains(_editingPalette) ? _editingPalette : null,
            3 => CurrentSound,
            _ => null,
        };
        return new UndoView(tab, item);
    }

    /// <summary>Before undo/redo: shows the tab the edit was made on.</summary>
    private void GoToUndoTab(UndoView? view)
    {
        if (view is not null && Tabs is not null && Tabs.SelectedIndex != view.Tab) Tabs.SelectedIndex = view.Tab;
    }

    /// <summary>After undo/redo: reselects what was selected then, if it still exists and isn't already selected.</summary>
    private void GoToUndoItem(UndoView? view)
    {
        switch (view?.Item)
        {
            case Sprite s when !ReferenceEquals(s, _current) && _file?.PositionOf(s) is int pos and >= 0:
                SelectSprite(pos);
                break;
            case Air.AnimationAction a when !ReferenceEquals(a, _action) && _air?.Actions.Contains(a) == true:
                SelectAction(a);
                break;
            case Palette palette when _file is null && _standalonePalettes.Contains(palette)
                && !ReferenceEquals(palette, _editingPalette):
                _standalonePaletteOverride = _standalonePalettes.IndexOf(palette);
                RebuildPaletteList();
                _suppressEvents = true;
                PaletteList.SelectedIndex = _standalonePaletteOverride;
                _suppressEvents = false;
                _editingPalette = palette;
                _editingView = BigSwatches;
                RefreshPaletteTab();
                break;
            case Snd.SoundEntry snd when !ReferenceEquals(snd, CurrentSound) && _snd?.Sounds.Contains(snd) == true:
                JumpToSound(snd);
                break;
        }
    }

