                private ThemeVariant? _appliedThemeVariant;

                /// <summary>
                /// Publishes a filled theme dictionary in one step. Attaching and detaching
                /// the dictionary costs two resource-change notifications; the same ~100
                /// assignments written key by key into Application.Resources cost one each,
                /// and every one of them re-resolves the DynamicResource bindings in the
                /// window. The new dictionary goes in before the old one comes out so no
                /// lookup can momentarily miss. Nothing else may declare these keys in
                /// Application.Resources directly: a dictionary's own entries outrank its
                /// merged dictionaries and would shadow every value set here.
                /// </summary>
                private static void AttachThemeResources(ResourceDictionary next)
                {
                    var host = Application.Current!.Resources;
                    host.MergedDictionaries.Add(next);
                    if (_currentThemeResources is not null) host.MergedDictionaries.Remove(_currentThemeResources);
                    _currentThemeResources = next;
                }

