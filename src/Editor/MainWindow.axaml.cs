    // Width a collapsed side panel shrinks to — just enough for the toggle button.
    private const double CollapsedPanelWidth = 32;

    // Remembers each panel's width from just before it collapsed, keyed by its body control.
    private readonly Dictionary<Control, GridLength> _preCollapseWidths = new();

    /// <summary>Folds a side panel to a thin strip, or restores it, via its toggle button.
    /// The header label hides with the body: the collapsed strip is too narrow to show it.
    /// expandedDefault is what to restore to if there's no pre-collapse width on record —
    /// which happens after Reset Panel Sizes clears that record while something is
    /// collapsed; falling back to the panel's own *current* (collapsed) width there would
    /// make Restore a no-op, leaving the panel stuck invisible with no way back.</summary>
    private void ToggleSidePanel(Grid grid, int column, Control body, Button toggle,
        GridSplitter splitter, Control? label, string collapsedGlyph, string expandedGlyph, GridLength expandedDefault)
    {
        var col = grid.ColumnDefinitions[column];
        if (body.IsVisible)
        {
            _preCollapseWidths[body] = col.Width;
            col.Width = new GridLength(CollapsedPanelWidth);
            body.IsVisible = false;
            if (label is { } l) l.IsVisible = false;
            splitter.IsEnabled = false;
            toggle.Content = expandedGlyph;
        }
        else
        {
            col.Width = _preCollapseWidths.TryGetValue(body, out var w) ? w : expandedDefault;
            body.IsVisible = true;
            if (label is { } l) l.IsVisible = true;
            splitter.IsEnabled = true;
            toggle.Content = collapsedGlyph;
        }
        SyncFloatButtons();
    }

    /// <summary>Same idea as ToggleSidePanel, but for a horizontal strip above a canvas — collapses/restores a row's height instead of a column's width. Every top panel's natural size is Auto, so unlike ToggleSidePanel there's no per-caller default to pass.</summary>
    private void ToggleTopPanel(Grid grid, int row, Control body, Button toggle,
        string collapsedGlyph, string expandedGlyph)
    {
        var r = grid.RowDefinitions[row];
        if (body.IsVisible)
        {
            _preCollapseWidths[body] = r.Height;
            r.Height = new GridLength(0);
            body.IsVisible = false;
            toggle.Content = expandedGlyph;
        }
        else
        {
            r.Height = _preCollapseWidths.TryGetValue(body, out var h) ? h : GridLength.Auto;
            body.IsVisible = true;
            toggle.Content = collapsedGlyph;
        }
    }

