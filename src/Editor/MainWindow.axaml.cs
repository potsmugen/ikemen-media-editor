    protected override void OnKeyDown(KeyEventArgs e)
    {
        // A multi-selection action holds the busy lock; ignore every shortcut
        // until it releases, so no menu-like action can run underneath it.
        if (_busy) { e.Handled = true; return; }

        // Ctrl+S first, before the text-box carve-out below, so it also
        // saves while e.g. a frame cell or the filter box has focus.
        if (e.Key == Key.S && e.KeyModifiers == KeyModifiers.Control)
        {
            SaveCurrentTab();
            e.Handled = true;
            return;
        }
        if (e.Key == Key.S && e.KeyModifiers == (KeyModifiers.Control | KeyModifiers.Shift))
        {
            _ = SaveAsCurrentTab(); // each branch logs its own failures
            e.Handled = true;
            return;
        }
        // Ctrl+F also jumps here first, so Find works no matter what has focus.
        if (e.Key == Key.F && e.KeyModifiers == KeyModifiers.Control)
        {
            OnFocusFind(this, new RoutedEventArgs());
            e.Handled = true;
            return;
        }

        // Let text and number boxes have their keys.
        if (KeyFocus() is TextBox or NumericUpDown)
        {
            if (e.Key == Key.Escape) SpriteList.Focus();
            base.OnKeyDown(e);
            return;
        }

        // Delete in an open Open Recent menu removes that entry (see TryRemoveRecent).
        if (e.Key == Key.Delete && TryRemoveRecent())
        {
            e.Handled = true;
            return;
        }

        // Menu InputGesture text does not bind shortcuts in Avalonia.
        if (e.KeyModifiers == KeyModifiers.Control)
        {
            switch (e.Key)
            {
                case Key.Z: OnUndo(this, new RoutedEventArgs()); e.Handled = true; return;
                case Key.Y: OnRedo(this, new RoutedEventArgs()); e.Handled = true; return;
                case Key.O: OnOpen(this, new RoutedEventArgs()); e.Handled = true; return;
                case Key.D0: OnResetView(this, new RoutedEventArgs()); e.Handled = true; return;
                case Key.D9: OnZoomFit(this, new RoutedEventArgs()); e.Handled = true; return;
                case Key.M: OnToggleMask(this, new RoutedEventArgs()); e.Handled = true; return;
                case Key.B: OnToggleBounds(this, new RoutedEventArgs()); e.Handled = true; return;
                case Key.G: OnToggleGuides(this, new RoutedEventArgs()); e.Handled = true; return;
                case Key.A: SelectAllCurrentList(); e.Handled = true; return;
                case Key.C when Tabs?.SelectedIndex == 2: CopyFrames(); e.Handled = true; return;
                case Key.V when Tabs?.SelectedIndex == 2: PasteFrames(); e.Handled = true; return;
            }
        }
        if (e.KeyModifiers == (KeyModifiers.Control | KeyModifiers.Shift) && e.Key == Key.O)
        {
            OnOpenCharacter(this, new RoutedEventArgs());
            e.Handled = true;
            return;
        }
        if (e.Key == Key.Escape && (_pickingFor is not null || _palettePickingFor is not null))
        {
            CancelPick(restoreSelection: true);
            CancelPaletteLinkPick(restoreSelection: true);
            StatusText.Text = "Canceled.";
            e.Handled = true;
            return;
        }

        // Focused timeline: Left/Right step frames like Prev/Next.
        if (Tabs?.SelectedIndex == 2 && TimelineView.IsFocused && e.KeyModifiers == KeyModifiers.None
            && e.Key is Key.Left or Key.Right)
        {
            StepFrame(e.Key == Key.Left ? -1 : 1);
            e.Handled = true;
            return;
        }

        if (Tabs?.SelectedIndex == 2 && AnimCanvas.IsFocused
            && AnimCanvas.SelectedBoxes.Count > 0)
        {
            (int X, int Y)? delta = e.Key switch
            {
                Key.Left => (-1, 0),
                Key.Right => (1, 0),
                Key.Up => (0, -1),
                Key.Down => (0, 1),
                _ => null,
            };
            if (delta is { } move)
            {
                AnimCanvas.NudgeSelectedBoxes(move.X, move.Y);
                e.Handled = true;
                return;
            }
        }

        if (e.Key == Key.Delete && KeyFocus() is Visual focused)
        {
            var list = focused.FindAncestorOfType<ListBox>(true);
            if (list == SpriteList) OnDeleteSprite(this, new RoutedEventArgs());
            else if (list == PaletteList) OnDeletePalette(this, new RoutedEventArgs());
            else if (list == ActionList) OnDeleteAction(this, new RoutedEventArgs());
            else if (list == FrameTableList || list == FrameList) OnRemoveFrame(this, new RoutedEventArgs());
            else if (list == SoundList) OnDeleteSound(this, new RoutedEventArgs());
            else list = null;
            if (list is not null)
            {
                e.Handled = true;
                return;
            }
        }

        if (e.Key == Key.Delete && Tabs?.SelectedIndex == 2 && AnimCanvas.SelectedBox >= 0)
        {
            DeleteSelectedBoxes();
            e.Handled = true;
            return;
        }

        // No box selected: Delete removes the current frame instead.
        if (e.Key == Key.Delete && Tabs?.SelectedIndex == 2)
        {
            OnRemoveFrame(null, new RoutedEventArgs());
            e.Handled = true;
            return;
        }

        // Arrows, Page Up/Down and Home/End belong to the focused list or control; nothing steps a list behind it.
        // With nothing focused they'd wander into the menus, so they hand focus to the tab's list instead.
        if (e.Key is Key.Left or Key.Right or Key.Up or Key.Down or Key.PageUp or Key.PageDown or Key.Home or Key.End
            && KeyFocus() is null)
        {
            FocusTabList();
            e.Handled = true;
            return;
        }

        switch (e.Key)
        {
            case Key.Add or Key.OemPlus: SpriteCanvas.StepZoom(1); break;
            case Key.Subtract or Key.OemMinus: SpriteCanvas.StepZoom(-1); break;
            default: base.OnKeyDown(e); return;
        }
        e.Handled = true;
    }

