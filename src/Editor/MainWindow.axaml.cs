    /// <summary>
    /// A palette that belongs to the session, not to any file. It exists purely
    /// so there is somewhere to hold or experiment with colors while editing a
    /// real one; nothing here is saved, and edits to it never touch undo or the
    /// dirty flag.
    /// </summary>
    private readonly Palette _scratchPalette = new()
    {
        Colors = Enumerable.Repeat(new Rgba(0, 0, 0, 0), 256).ToArray(),
    };

    /// <summary>Whichever palette the RGBA boxes currently edit, and which grid showed it.</summary>
    private Palette? _editingPalette;
    private PaletteView? _editingView;
    private int _selectedSwatch = -1;

    private async void OnSwatchClicked(Palette? pal, PaletteView view, int index)
    {
        try
        {
            if (pal is null || index >= pal.Colors.Length) return;

            // Eyedropper, checked before anything else: ApplyPickedColor owns the
            // pending-adjust state that the rest of this method is about to reset.
            if (EyedropperWants(view))
            {
                if (ApplyPickedColor(pal.Colors[index])) DisarmEyedropper();
                return;
            }

            if (_armedReplaceSlot is int slot) { SetReplaceSlot(slot, index); return; }

            var c = pal.Colors[index];
            if (SwatchInfo is not null) UpdateSwatchInfo(pal, index);

            // The sprite panel's swatches are read-only: they show and paint with the color,
            // but never take the Palettes tab's selection or color editor.
            if (!view.ReadOnly)
            {
                // One grid is the one being edited (_editingView), and every color operation
                // scopes to _editingView.Selection. A selection left on another grid would look
                // like it was included when no operation would ever touch it.
                ClearOtherSwatchSelections(view);

                // Any slider preview that wasn't committed is lost the moment you
                // click elsewhere — same palette or not — same as pressing Reset.
                // No dialog: Commit is the one and only way to keep it.
                DiscardPendingColorAdjust();

                _editingPalette = pal;
                _editingView = view;
                _selectedSwatch = index;

                // Clicking the palette-tab preview (BigSwatches) also highlights that
                // palette's own row in the list, since ActivePalette() can be showing
                // the current sprite's palette even when nothing there is selected.
                // This must only touch the list's own selection, never _paletteOverride
                // — that also drives ActivePalette(), which the Sprites tab's canvas and
                // its own Swatches view read too, so setting it here would make clicking
                // a color on the Palette tab silently change what the Sprites tab shows.
                if (ReferenceEquals(view, BigSwatches) && _file is not null && !ReferenceEquals(pal, _scratchPalette))
                    HighlightPaletteInList(pal);

                _suppressEvents = true;
                RSlider.Value = c.R; GSlider.Value = c.G; BSlider.Value = c.B; ASlider.Value = c.A;
                _suppressEvents = false;
                ColorEditor.IsEnabled = true;
                ASlider.IsEnabled = CanEditPaletteAlpha(pal);
                ResetColorAdjustBase();
            }

            SpriteCanvas.PaintColorIndex = index;
        }
        catch (Exception ex)
        {
            await Failed("OnSwatchClicked", ex);
        }
    }

