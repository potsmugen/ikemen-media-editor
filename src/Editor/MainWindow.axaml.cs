    /// <summary>
    /// Recolors the app's own panels/text, retints the menu bar and its
    /// dropdowns to the same hue (by overriding Fluent's own
    /// MenuFlyoutPresenter*/MenuFlyoutItem* brush resources — the same
    /// resource-dictionary trick as the app's own Theme* keys, just aimed at
    /// keys Fluent already reads), and flips native chrome elsewhere (other
    /// buttons, scrollbars) between light and dark to roughly match. See the
    /// note in App.axaml for the parts still left on generic Fluent chrome.
    /// <para>
    /// A Fluent control is only themed if every key its template reads has been
    /// overridden here. Each control uses its own key family, so covering the
    /// menus says nothing about the ComboBox (ComboBox*), and a popup left on
    /// Fluent's stock colors is the failure mode to watch for: it looks right
    /// in a theme that happens to match Fluent's default and wrong in the rest.
    /// </para>
    /// </summary>
    /// <summary>Blends <paramref name="a"/> toward <paramref name="b"/> by <paramref name="t"/> (0 = a, 1 = b). Used to derive hairline colors from a theme's text and list colors.</summary>
        private static Color Mix(Color a, Color b, double t) => Color.FromRgb(
            (byte)Math.Round(a.R + (b.R - a.R) * t),
            (byte)Math.Round(a.G + (b.G - a.G) * t),
            (byte)Math.Round(a.B + (b.B - a.B) * t));

        /// <summary>
            /// Points the rest of Fluent's controls at the theme. Each control reads its
            /// own key family — Button*, TextControl* (TextBox and NumericUpDown),
            /// TabItemHeader*, Slider*, CheckBox* — and a family left alone keeps that
            /// control on Fluent's stock light/dark colors. Those follow the light/dark
            /// variant so they stay legible, but they ignore the specific hue, which is
            /// what made a Blue or Amber field look stock-neutral.
            /// Covers the states the app can actually reach; a control that gained a new
            /// state later shows Fluent's color for that one state only.
            /// </summary>
            private static void ApplyControlColors(IResourceDictionary res, IBrush panel, IBrush field, IBrush hover, IBrush text, IBrush muted, IBrush dim, IBrush accent, IBrush activeButton, IBrush activeText)
            {
                // Button (and ToggleButton, whose theme is based on it).
                res["ButtonBackground"] = field;
                res["ButtonForeground"] = text;
                res["ButtonBorderBrush"] = dim;
                res["ButtonBackgroundPointerOver"] = hover;
                res["ButtonBorderBrushPointerOver"] = muted;
                res["ButtonForegroundPointerOver"] = text;
                res["ButtonBackgroundPressed"] = field;
                res["ButtonBorderBrushPressed"] = muted;
                res["ButtonForegroundPressed"] = text;
                res["ButtonBackgroundDisabled"] = field;
                res["ButtonBorderBrushDisabled"] = dim;
                res["ButtonForegroundDisabled"] = dim;

                res["ToggleButtonBackground"] = field;
                res["ToggleButtonBorderBrush"] = dim;
                res["ToggleButtonForeground"] = text;
                res["ToggleButtonBackgroundPointerOver"] = hover;
                res["ToggleButtonBorderBrushPointerOver"] = muted;
                res["ToggleButtonForegroundPointerOver"] = text;
                res["ToggleButtonBackgroundPressed"] = field;
                res["ToggleButtonBorderBrushPressed"] = muted;
                res["ToggleButtonForegroundPressed"] = text;
                res["ToggleButtonBackgroundDisabled"] = field;
                res["ToggleButtonBorderBrushDisabled"] = dim;
                res["ToggleButtonForegroundDisabled"] = dim;

                res["ToggleButtonBackgroundChecked"] = activeButton;
                res["ToggleButtonBorderBrushChecked"] = activeButton;
                res["ToggleButtonForegroundChecked"] = activeText;
                res["ToggleButtonBackgroundCheckedPointerOver"] = activeButton;
                res["ToggleButtonBorderBrushCheckedPointerOver"] = activeButton;
                res["ToggleButtonForegroundCheckedPointerOver"] = activeText;
                res["ToggleButtonBackgroundCheckedPressed"] = activeButton;
                res["ToggleButtonBorderBrushCheckedPressed"] = activeButton;
                res["ToggleButtonForegroundCheckedPressed"] = activeText;
                res["ToggleButtonBackgroundCheckedDisabled"] = activeButton;
                res["ToggleButtonBorderBrushCheckedDisabled"] = activeButton;
                res["ToggleButtonForegroundCheckedDisabled"] = dim;

                // RepeatButton, which the +/- spinners are (see the ButtonSpinner
                // template in App.axaml). Its theme reads the RepeatButton* family,
                // not Button*, so without these the spinner's two buttons keep
                // Fluent's stock colors and ignore the active theme's hue -- the
                // gap the Button block above leaves by covering only Button*.
                // Same color mapping as Button, so the pair still look alike.
