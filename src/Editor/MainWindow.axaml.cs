    /// <summary>Expands the current tab's side panels and sizes them to fit their contents. Other tabs are left alone.</summary>
    private void OnResetPanelSizes(object? sender, RoutedEventArgs e)
    {
        // ColumnDefinition itself is layout metadata, not part of the visual
        // tree, so x:Name on one doesn't generate a field the way it does for
        // a Control. The Grid holding them is a real control, so it gets the
        // field, and the columns are reached by their fixed position within it.
        static void Reset(Grid grid, params GridLength[] widths)
        {
            for (int i = 0; i < widths.Length && i < grid.ColumnDefinitions.Count; i++)
                grid.ColumnDefinitions[i].Width = widths[i];
        }

        var star = new GridLength(1, GridUnitType.Star);
        double separatorWidth = Settings.Checked(nameof(Settings.PanelSeparatorWidth), _settings.PanelSeparatorWidth,
            Settings.DefaultPanelSeparatorWidth, v => v >= 1 && v <= Settings.DefaultPanelSeparatorWidthMax);
        var splitter = new GridLength(separatorWidth);
        var bodies = new List<(Control Body, Button Toggle, Control Label, string Glyph)>();
        Grid grid;
        ResetFloatingPanels(Tabs?.SelectedIndex ?? 0); // reset means the default layout, docked

        switch (Tabs?.SelectedIndex ?? 0)
        {
            case 0: // Sprites
                grid = SpritesGrid;
                Reset(SpritesGrid, new GridLength(300), splitter, star, splitter, new GridLength(300));
                SpritePaletteBody.RowDefinitions[0].Height = GridLength.Auto;
                SpritePaletteBody.RowDefinitions[1].Height = splitter;
                SpritePaletteBody.RowDefinitions[2].Height = star;
                SpriteCanvasArea.RowDefinitions[1].Height = GridLength.Auto;
                PaintPanelBody.IsVisible = PaintPanelLabel.IsVisible = true;
                OnionPanelBody.IsVisible = true;
                PaintPanelToggle.Content = "▶";
                OnionPanelToggle.Content = "▲";
                _preCollapseWidths.Remove(OnionPanelBody);
                bodies.Add((SpriteListBody, SpriteListToggle, SpriteListLabel, "◀"));
                bodies.Add((SpritePaletteBody, SpritePaletteToggle, SpritePaletteLabel, "▶"));
                SpritesLeftSplitter.IsEnabled = SpritesRightSplitter.IsEnabled = true;
                _settings.SpritesListWidth = _settings.SpritesPaletteWidth = null;
                Swatches.CellSize = 0;
                Swatches.InvalidateMeasure();
                break;
            case 1: // Palettes
                grid = PalettesGrid;
                Reset(PalettesGrid, new GridLength(220), splitter, star, splitter, star);
                PaletteSwatchEditorGrid.RowDefinitions[0].Height = star;
                PaletteSwatchEditorGrid.RowDefinitions[1].Height = splitter;
                PaletteSwatchEditorGrid.RowDefinitions[2].Height = star;
                PaletteSwatchEditorGrid.ColumnDefinitions[0].Width = star;
                PaletteSwatchEditorGrid.ColumnDefinitions[1].Width = splitter;
                PaletteSwatchEditorGrid.ColumnDefinitions[2].Width = star;
                PaletteRightBody.RowDefinitions[1].Height = splitter;
                bodies.Add((PaletteListBody, PaletteListToggle, PaletteListLabel, "◀"));
                bodies.Add((PaletteRightBody, PaletteRightToggle, PaletteRightLabel, "▶"));
                PalettesLeftSplitter.IsEnabled = PalettesRightSplitter.IsEnabled = true;
                _settings.PalettesListWidth = null;
                foreach (var view in new[] { BigSwatches, ScratchSwatches })
                {
                    view.CellSize = 0;
                    view.InvalidateMeasure();
                }
                break;
            case 2: // Animations
                grid = AnimationsGrid;
                Reset(AnimationsGrid, new GridLength(250), splitter, star, splitter, new GridLength(260));
                AnimationsGrid.RowDefinitions[1].Height = splitter;
                FramePanelBody.RowDefinitions[1].Height = splitter;
                bodies.Add((ActionListBody, ActionListToggle, ActionListLabel, "◀"));
                bodies.Add((FramePanelBody, FramePanelToggle, FramePanelLabel, "▶"));
                AnimLeftSplitter.IsEnabled = AnimRightSplitter.IsEnabled = true;
                _settings.AnimActionsWidth = _settings.AnimFramePanelWidth = null;
                break;
            case 3: // Sounds
                grid = SoundsGrid;
                Reset(SoundsGrid, new GridLength(280), splitter, star);
                SoundRightGrid.RowDefinitions[1].Height = new GridLength(180); // waveform panel, as in the XAML
                SoundRightGrid.RowDefinitions[2].Height = splitter;
                bodies.Add((SoundListBody, SoundListToggle, SoundListLabel, "◀"));
                SoundsSplitter.IsEnabled = true;
                _settings.SoundsListWidth = null;
                _settings.SoundsWaveformHeight = null;
                break;
            default:
                return;
        }

        // A folded panel would otherwise stay folded at its old (now wrong) width.
        foreach (var (body, toggle, label, glyph) in bodies)
        {
            _preCollapseWidths.Remove(body);
            body.IsVisible = true;
            label.IsVisible = true;
            toggle.Content = glyph;
        }
        SyncFloatButtons();

        // A reset should stick, not just look reset until the saved sizes get
        // re-applied on the next launch.
        _settings.Save();

        // Fixed widths above are the fallback; fit this tab's panels once laid out.
        _pendingPanelFit.Add(grid);
        FitPanelsForTab(Tabs?.SelectedIndex ?? 0);

        StatusText.Text = "Panel sizes reset.";
    }

    // Tab grids still waiting to be fitted: a tab's content isn't templated until it's shown.
    private readonly HashSet<Grid> _pendingPanelFit = new();

    /// <summary>Fits the given tab's side panels after the next layout pass, if a reset left them pending.</summary>
    private void FitPanelsForTab(int tab)
    {
        Grid? grid = tab switch { 0 => SpritesGrid, 1 => PalettesGrid, 2 => AnimationsGrid, 3 => SoundsGrid, _ => null };
        if (grid is null || !_pendingPanelFit.Contains(grid)) return;
        Dispatcher.UIThread.Post(() => FitSidePanels(grid), DispatcherPriority.Background);
    }

    /// <summary>Sets each pixel-sized side column (0 and 4) to its panel's natural width, within PanelFitMinWidth and PanelFitMaxPercent of the tab.</summary>
    private void FitSidePanels(Grid grid)
    {
        if (!grid.IsEffectivelyVisible || grid.Bounds.Width <= 0) return; // stays pending until shown
        _pendingPanelFit.Remove(grid);
        double min = Settings.Checked(nameof(Settings.PanelFitMinWidth), _settings.PanelFitMinWidth,
            Settings.DefaultPanelFitMinWidth, v => double.IsFinite(v) && v >= 0);
        double pct = Settings.Checked(nameof(Settings.PanelFitMaxPercent), _settings.PanelFitMaxPercent,
            Settings.DefaultPanelFitMaxPercent, v => double.IsFinite(v) && v > 0 && v <= 100);
        double max = Math.Max(min, grid.Bounds.Width * pct / 100);
        foreach (int col in new[] { 0, 4 })
        {
            if (col >= grid.ColumnDefinitions.Count || !grid.ColumnDefinitions[col].Width.IsAbsolute) continue;
            var panel = grid.Children.FirstOrDefault(c => Grid.GetColumn(c) == col && c is not GridSplitter);
            if (panel is null || !panel.IsVisible) continue; // floating
            // Trimmed or wrapped text (e.g. a long action comment) fits any width, so it mustn't widen the panel.
            var squeezed = panel.GetVisualDescendants().OfType<TextBlock>()
                .Where(t => t.TextTrimming != TextTrimming.None || t.TextWrapping != TextWrapping.NoWrap)
                .Select(t => (Block: t, t.MaxWidth)).ToList();
            foreach (var s in squeezed) s.Block.MaxWidth = 0;
            // Finite height so virtualised lists only realize the rows on screen, not every item.
            panel.Measure(new Size(double.PositiveInfinity, Math.Max(panel.Bounds.Height, 1)));
            foreach (var s in squeezed) s.Block.MaxWidth = s.MaxWidth;
            double w = Math.Clamp(Math.Ceiling(panel.DesiredSize.Width), min, max);
            grid.ColumnDefinitions[col].Width = new GridLength(w);
        }
    }

